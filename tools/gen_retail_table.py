#!/usr/bin/env python3
"""gen_retail_table.py -- the retail CODE address -> wasm function table, generated from the module's own objects.

The retail data image (loaded at run time) holds retail CODE addresses: GCC 2.9x vtables, `__CTOR_LIST__`, callbacks,
event tables. On the PS2 those addresses were the functions; in the wasm module a function pointer is a TABLE INDEX. This
script lists every function the game's objects DEFINE under a retail name (symbol_addrs.txt `type:func`, exact name or
`<name>_n32`, the C++ side of an EABI thunk) and writes a C file holding one array of `{retail address, &function}`:

  * taking every address forces wasm-ld to give each function a table slot and keeps it out of --gc-sections;
  * the array is exported (`te_retail_functions`, `te_retail_function_count`) so the runner, after loading the image,
    rewrites every 4-byte word of .data/.rodata/.sdata that equals a listed retail address into that function's table
    index -- and reports every retail code address it finds that NO function claims (an unported body).

    gen_retail_table.py --game GAME_ROOT --nm LLVM_NM --out retail_table.c [--json retail_table.json] obj1.o ...
"""
import argparse
import json
import re
import os
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rspfile  # noqa: E402


def read_symbol_addrs(path):
    syms = {}
    for line in path.read_text().splitlines():
        m = re.match(r"(\w+)\s*=\s*0x([0-9A-Fa-f]+);\s*(?://\s*(.*))?", line)
        if m:
            rest = m.group(3) or ""
            syms[m.group(1)] = (int(m.group(2), 16), "type:func" in rest)
    return syms


def defined_functions(nm, objects, rsp):
    defined = set()
    r = subprocess.run([nm, *rspfile.tool_args(["--defined-only", *objects], rsp)], capture_output=True, text=True)
    for line in r.stdout.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in ("T", "t", "W"):
            defined.add(parts[2])
    return defined


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--game", required=True)
    ap.add_argument("--nm", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--json", default=None)
    ap.add_argument("--host-out", default=None, help="C file for the HOST: every retail function start (symbol_addrs.txt)")
    ap.add_argument("objects", nargs="+")
    a = ap.parse_args(rspfile.expand_argv(sys.argv[1:]))

    syms = read_symbol_addrs(Path(a.game) / "symbol_addrs.txt")
    defined = defined_functions(a.nm, a.objects, a.out + ".nm.rsp")

    entries = {}  # addr -> symbol to take the address of
    n32_only = []
    for name, (addr, is_func) in syms.items():
        if not is_func:
            continue
        if name in defined:
            entries[addr] = name
        elif name + "_n32" in defined:
            entries[addr] = name + "_n32"
            n32_only.append(name)
    # Functions the decomp names by ADDRESS alone (`RETAIL(func_002A3110)`: 131 bodies symbol_addrs.txt does not list,
    # SaveDevice::SaveSpace among them -- its vtable slot stayed a retail address, the first trap after the slot thunks):
    # a defined `func_XXXXXXXX` / `FUN_xxxxxxxx` (or its `_n32` side) inside the retail code range claims that address.
    by_name = []
    for name in sorted(defined):
        m = re.fullmatch(r"(?:func|FUN)_([0-9A-Fa-f]{8})(_n32)?", name)
        if not m:
            continue
        addr = int(m.group(1), 16)
        if not (0x00100000 <= addr < 0x002D9D90) or addr in entries:
            continue
        if m.group(2) and name[:-4] in defined:
            continue  # the exact name is taken below / above
        entries[addr] = name
        by_name.append(name)
    missing = sorted(n for n, (addr, f) in syms.items() if f and addr not in entries)

    addrs = sorted(entries)
    L = ["// GENERATED by tools/gen_retail_table.py -- DO NOT EDIT. Retail code address -> function, for the runner's patcher.",
         f"// {len(addrs)} retail functions defined by the module; {len(missing)} retail function addresses have no body here.",
         "typedef unsigned int te_u32;", "typedef void (*te_fn)(void);",
         "struct te_retail_function { te_u32 address; te_fn function; };"]
    for i, addr in enumerate(addrs):
        L.append(f'extern void te_rf_{i}(void) __asm__("{entries[addr]}");')
    L.append("__attribute__((used, visibility(\"default\"))) const struct te_retail_function te_retail_functions[] = {")
    for i, addr in enumerate(addrs):
        L.append(f"    {{0x{addr:08X}u, &te_rf_{i}}},")
    L.append("};")
    L.append(f"__attribute__((used, visibility(\"default\"))) const te_u32 te_retail_function_count = {len(addrs)}u;")
    L.append("")
    Path(a.out).write_text("\n".join(L))
    if a.host_out:
        starts = sorted({addr for name, (addr, f) in syms.items() if f} | set(entries))
        H = ["// GENERATED by tools/gen_retail_table.py -- DO NOT EDIT. Every retail function start (symbol_addrs.txt type:func",
             "// + the address-named func_XXXXXXXX bodies the module defines),",
             "// for the runner's patcher to tell an unported body from a stray integer.", "#include <stdint.h>",
             f"const uint32_t te_known_function_starts[{len(starts)}] = {{"]
        for i in range(0, len(starts), 8):
            H.append("    " + ", ".join(f"0x{x:08X}u" for x in starts[i:i + 8]) + ",")
        H += ["};", f"const uint32_t te_known_function_start_count = {len(starts)}u;", ""]
        Path(a.host_out).write_text("\n".join(H))
    if a.json:
        Path(a.json).write_text(json.dumps({"count": len(addrs), "n32_only": n32_only, "by_name": by_name, "missing": missing,
                                            "entries": {f"0x{k:08X}": v for k, v in entries.items()}}, indent=1))
    print(f"gen_retail_table: {len(addrs)} functions ({len(n32_only)} via _n32, {len(by_name)} address-named), "
          f"{len(missing)} retail function addresses unported -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
