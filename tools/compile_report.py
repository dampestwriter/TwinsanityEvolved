#!/usr/bin/env python3
"""compile_report.py -- tools/compile_report.md: which game TUs compile to wasm32 with ZERO edits, what te_cxx.py had to
rewrite per file, the module's link facts, and every blocker (per file) that remains.

    compile_report.py --reports DIR --game GAME --module-report module_report.json --retail-table retail_table.json --out compile_report.md
"""
import argparse
import json
import re
from pathlib import Path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reports", required=True)
    ap.add_argument("--game", required=True)
    ap.add_argument("--module-report", required=True)
    ap.add_argument("--retail-table", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    reps = []
    for p in sorted(Path(a.reports).glob("*.json")):
        r = json.load(open(p))
        reps.append(r)
    game_root = str(Path(a.game).resolve())
    def rel(s):
        s = str(Path(s).resolve()) if Path(s).exists() else s
        return s.replace(game_root + "/", "game/")
    game = [r for r in reps if "game/src/" in rel(r["src"]) and "platform/ps2" not in rel(r["src"])]
    libc = [r for r in reps if "platform/ps2" in rel(r["src"])]
    plat = [r for r in reps if "platform/nativeee" in rel(r["src"]) or "seam_forwarders" in rel(r["src"])]
    ok_game = [r for r in game if r["ok"]]
    mod = json.load(open(a.module_report)) if Path(a.module_report).exists() else {}
    tab = json.load(open(a.retail_table)) if Path(a.retail_table).exists() else {}

    tot = {"fences": 0, "thunks": 0, "raw": 0, "touch": 0, "lqsq": 0, "trampoline": 0, "unrec": 0}
    rows = []
    for r in game + libc:
        w = r.get("rewrites") or {}
        tot["fences"] += w.get("fences", 0); tot["thunks"] += len(w.get("thunks_export", []))
        tot["raw"] += len(w.get("raw_blocks", [])); tot["touch"] += w.get("touch", 0); tot["lqsq"] += w.get("lqsq", 0)
        tot["trampoline"] += w.get("trampoline_f_renamed", 0); tot["unrec"] += w.get("unrecognised_asm", 0)
        notes = []
        if w.get("fences"): notes.append(f'`"+f"` fence x{w["fences"]} -> `"+m"`')
        if w.get("thunks_export"): notes.append(f'EABI thunk x{len(w["thunks_export"])} -> alias')
        for b in w.get("raw_blocks", []):
            if b["aliases"]: notes.append("MIPS block " + ", ".join(f"`{x}`->`{y}`" for x, y in b["aliases"]))
            for s in b["runtime_provided"]: notes.append(f"MIPS block `{s}` -> runner import")
        if w.get("touch"): notes.append("`lb` prefetch -> no-op")
        if w.get("lqsq"): notes.append("`lq/sq` -> 16-byte memcpy")
        if w.get("kept_portable_asm"): notes.append(f"portable `asm(\"\" : \"=m\")` kept x{w['kept_portable_asm']}")
        if w.get("unrecognised_asm"): notes.append(f"**{w['unrecognised_asm']} asm statement(s) NOT rewritten**")
        errs = [re.sub(r"^.*?error: ", "", e) for e in r.get("errors", [])]
        rows.append((rel(r["src"]), "ok" if r["ok"] else "**FAIL**", "; ".join(notes) or "none", "; ".join(errs[:3])))

    L = ["# TwinsanityEvolved -- game TU compile report (wasm32, ZERO edits to game code)", "",
         "Generated by `tools/compile_report.py` from the per-TU reports of `tools/te_cxx.py` (refresh: `tools/ci/build_all.sh`).", "",
         "## Summary", "",
         f"- Game TUs (`game/src/game/*.cpp`, `game/src/*.cpp`): **{len(ok_game)} / {len(game)}** compile to wasm32 objects.",
         f"- Kept decomp libc (`src/platform/ps2/{{libc,libm,malloc}}.cpp`): {sum(r['ok'] for r in libc)} / {len(libc)}.",
         f"- platform/nativeee wasm side + generated forwarders: {sum(r['ok'] for r in plat)} / {len(plat)}.",
         f"- Rewrites applied by te_cxx.py, total: `\"+f\"` fences {tot['fences']}, EABI thunks -> aliases {tot['thunks']}, "
         f"raw MIPS blocks {tot['raw']}, `lb` prefetch {tot['touch']}, `lq/sq` copy {tot['lqsq']}, `CallEabiFloat` label (abi.h, once per TU) {tot['trampoline']}; "
         f"asm statements left unrewritten: {tot['unrec']}.", ""]
    if mod:
        L += [f"- Module: {mod.get('functions')} functions, {mod.get('table_entries')} in the indirect table, "
              f"{mod.get('import_count')} imports (every one in the seam of {mod.get('seam_size')}), "
              f"retail image at 0x{mod.get('image_segment_start', 0):X}; problems: {mod.get('problems') or 'none'}."]
    if tab:
        L += [f"- Retail functions with a body in the module: {tab.get('count')}; retail function addresses WITHOUT a body "
              f"(SDK/platform-ps2 bodies, listed below): {len(tab.get('missing', []))}."]
    L += ["", "## Blockers that remain (not fixable by the toolchain alone)", "",
          "1. **Signature mismatches** between declarations of the same retail function in different TUs (harmless on MIPS, a trap "
          "on wasm: wasm-ld routes the mismatched direct call to `unreachable`). Each needs a ONE-LINE declaration fix in the fork "
          "(owner of the file): `MoveShortFromS2toS1` declared `u16* (u16*, const u16*)` in behaviourevents/modelinstances/eventcallers/"
          "resources.h vs `void (u16*, const u16*)` in characterstate.cpp and commandsmotion.cpp; `FUN_00132ca8` declared `void "
          "LinkCharacters(PlayerCharacter*, PlayerCharacter*)` in player.h vs `u32 Link(CharacterAgent*)` in agents.h.",
          "2. **Retail function addresses without a body** (below): any that the retail DATA points at (vtables, callbacks) is reported "
          "by the runner's patcher as `unported` at run time and must be provided by the owning seam module (the `_Methods` vtables of "
          "renderer resources and `Font` are the graphics owner's; SDK rows are not reachable from data).",
          "3. **Movie**: Platform::Movie over the engine's decoder (skippable with --skip-movies).", ""]
    L += ["## Per file", "", "| file | wasm32 | te_cxx.py rewrites | errors |", "|---|---|---|---|"]
    for f, st, notes, errs in rows:
        L.append(f"| `{f}` | {st} | {notes} | {errs} |")
    if tab:
        L += ["", "## Retail function addresses with no body in the module", "",
              "Names from `game/symbol_addrs.txt` (`type:func`) that no object defines (plain or `_n32`): PS2SDK rows, retired "
              "functions, fragments and the PS2 platform arm's own bodies. Only the ones retail DATA points at matter (the runner "
              "lists those as `unported`).", "", "```"]
        miss = tab.get("missing", [])
        for i in range(0, len(miss), 6):
            L.append("  ".join(miss[i:i + 6]))
        L += ["```"]
    Path(a.out).write_text("\n".join(L) + "\n")
    print(f"compile_report: {len(ok_game)}/{len(game)} game TUs ok -> {a.out}")


if __name__ == "__main__":
    main()
