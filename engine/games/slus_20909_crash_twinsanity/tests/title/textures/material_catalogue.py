#!/usr/bin/env python3
"""Generate/check the immutable proof data, never asset bytes or decomp code."""
import argparse
import json
from pathlib import Path

REASONS = [
    "material-envelope", "texture-identity-varies", "particle", "sprite", "font",
    "potential-borrowed-hud", "shadow-default", "skin", "blend-skin", "sky",
    "opaque-reference", "missing-texture", "missing-material", "model-not-qualified",
    "no-rigid-or-placed-consumer", "shared-with-unowned-model",
]


def files(report):
    if not report["geometry_qualified"] or not report["certified"]:
        raise ValueError("no complete-model qualification")
    prefix = (
        "// Generated by material_catalogue.py; static IDs/digests, no original game content.\n"
        '#include "games/slus_20909_crash_twinsanity/hle/graphics/textures/material_catalogue.h"\n'
        "#include <iterator>\n\nnamespace title {\n")
    result = {"identity.cpp": (prefix +
        "MaterialCertificate::Archive MaterialCatalogue::Identity() {\n"
        "    return {\n"
        f'    "{report["archive_header_sha256"]}",\n'
        f'    "{report["archive_data_sha256"]}"\n'
        "    };\n}\n}  // namespace title\n")}
    accepted = []
    for row in report["certified"]:
        for sha in row["material_sha256"]:
            accepted.append(f'{{0x{row["material"]}, 0x{row["texture"]}, "{sha}", '
                            f'{str(row["texture_exclusive"]).lower()}}},')
    refused = []
    for mid, reasons in report["refused"].items():
        mask = sum(1 << REASONS.index(reason) for reason in reasons)
        refused.append(f"{{0x{mid}, 0x{mask:04x}}},")
    for name, rows, pieces in (("accepted", accepted, 4), ("refused", refused, 6)):
        stride = (len(rows) + pieces - 1) // pieces
        if stride > 985:
            raise ValueError("catalogue partition budget changed; review source layout")
        for i in range(pieces):
            typename = "MaterialCertificate::Entry" if name == "accepted" else "MaterialCatalogue::Refusal"
            method = name.title()
            result[f"{name}_{i}.cpp"] = (prefix +
                "namespace {\n" +
                f"constexpr {typename} rows[] = {{\n" +
                "\n".join(rows[i * stride:(i + 1) * stride]) + "\n};\n}  // namespace\n" +
                f"MaterialCatalogue::{method} MaterialCatalogue::{method}{i}() {{\n"
                "    return {rows, std::size(rows)};\n}\n}  // namespace title\n")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inventory", type=Path)
    parser.add_argument("directory", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    args.directory.mkdir(parents=True, exist_ok=True)
    for name, text in files(json.loads(args.inventory.read_text())).items():
        path = args.directory / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise ValueError(f"catalogue differs: {name}")
        else:
            path.write_text(text)
    print("material catalogue matches complete inventory" if args.check else "material catalogue generated")


if __name__ == "__main__":
    main()
