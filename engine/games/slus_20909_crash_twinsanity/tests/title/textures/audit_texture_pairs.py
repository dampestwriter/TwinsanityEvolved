#!/usr/bin/env python3
"""Enumerate every PSM/PSF pair in the retail archive: the complete UI texture
owner catalogue (texture ID -> material ID, kind) that TextureSelection's
widened policy keys on.

A picture file (`*.psm`: Startup\\Icons.psm 40 pairs, Language\\Titles\\*.psm 1,
every other 8 -- TR game/oleg.cpp ReadPicture, gamecontroller.cpp) and a font
file (`*.psf`: a count then the pages -- TR game/font.cpp Font::Read) declare
texture/material pairs whose material records are parsed with the source
Shader reader's exact layout (material_records.py). The pairs are static
archive data: no game execution, no runtime seen-set.

The generated `texture_pairs_catalogue/rows_N.cpp` partitions hold
`TexturePairs::Entry` rows sorted by texture ID (each chunk also carries its
material-sorted index); `identity.cpp` the archive fingerprints. `--check`
fails when the committed catalogue differs from the archive.
"""
import argparse
import collections
import hashlib
import json
import mmap
from pathlib import Path
import struct
import sys

from audit_texture_assets import archive_index, u32
import material_records as records

CHUNK = 700
BANNER = "// Generated by tests/title/textures/audit_texture_pairs.py; static IDs, no original game content.\n"
INCLUDE = '#include "games/slus_20909_crash_twinsanity/hle/graphics/textures/texture_pairs_catalogue.h"\n'


def pairs(archive):
    index = (archive / "CRASH.BH").read_bytes()
    header_sha = hashlib.sha256(index).hexdigest()
    rows = []
    with (archive / "CRASH.BD").open("rb") as stream, mmap.mmap(stream.fileno(), 0, access=mmap.ACCESS_READ) as data:
        data_sha = hashlib.sha256(data).hexdigest()
        for name, start, size in archive_index(index):
            ext = Path(name).suffix.lower()
            if ext not in (".psm", ".psf"):
                continue
            at = start
            if ext == ".psm":
                count = 40 if name.lower() == "startup\\icons.psm" else (
                    1 if name.lower().startswith("language\\titles\\") else 8)
            else:
                count = u32(data, at)
                at += 4
            for slot in range(count):
                texture, material_id = struct.unpack_from("<II", data, at)
                at += 8
                at += 4 + u32(data, at)
                parsed, at = records.material(data, at, start + size - at, complete=False)
                shaders = parsed["shaders"]
                # The owned Sprite/Text producers draw shaders[0] of a one-shader
                # type-0D material in the UI (24) or font (26) bucket with the
                # pair's own texture (TR draw2d.cpp Begin2D, text.cpp); anything
                # else is an unclassified pair and stops the catalogue.
                if (len(shaders) != 1 or shaders[0]["type"] != 0x0d or shaders[0]["texture"] != texture or
                        parsed["key"] != 0x10000000 or parsed["bucket"] != (24 if ext == ".psm" else 26)):
                    raise ValueError(f"unclassified pair material in {name} slot {slot}")
                rows.append(dict(texture=texture, material=material_id, kind="Font" if ext == ".psf" else "Picture",
                                 container=name, slot=slot))
    by_texture = collections.defaultdict(set)
    by_material = collections.defaultdict(set)
    for row in rows:
        by_texture[row["texture"]].add(row["material"])
        by_material[row["material"]].add(row["texture"])
    if any(len(v) != 1 for v in by_texture.values()) or any(len(v) != 1 for v in by_material.values()):
        raise ValueError("a UI texture or material is paired more than once")
    rows.sort(key=lambda r: r["texture"])
    return rows, header_sha, data_sha


def render(rows, header_sha, data_sha):
    files = {}
    chunks = [rows[i:i + CHUNK] for i in range(0, len(rows), CHUNK)]
    header = [
        "#pragma once", "", '#include "games/slus_20909_crash_twinsanity/hle/graphics/textures/texture_pairs.h"', "",
        "namespace title {", "",
        "// Private generated-data partitions; consumers use TexturePairs.",
        "class TexturePairsCatalogue {", "public:",
        "    struct Rows { const TexturePairs::Entry* data; const uint16_t* by_material; size_t size; };",
        f"    static constexpr size_t kChunks = {len(chunks)};",
        "    static const char* HeaderSha256();", "    static const char* DataSha256();",
        "    static Rows Chunk(size_t index);",
    ]
    for n in range(len(chunks)):
        header.append(f"    static Rows Rows{n}();")
    header += ["};", "", "}  // namespace title", ""]
    files["texture_pairs_catalogue.h"] = "\n".join(header)
    for n, chunk in enumerate(chunks):
        lines = [BANNER + INCLUDE + "#include <iterator>", "", "namespace title {", "namespace {",
                 "constexpr TexturePairs::Entry rows[] = {"]
        for row in chunk:
            lines.append(f"{{0x{row['texture']:08x}, 0x{row['material']:08x}, TexturePairs::Kind::{row['kind']}}},")
        lines.append("};")
        order = sorted(range(len(chunk)), key=lambda i: chunk[i]["material"])
        lines.append("constexpr uint16_t by_material[] = {")
        for i in range(0, len(order), 20):
            lines.append(", ".join(str(v) for v in order[i:i + 20]) + ",")
        lines += ["};", "}  // namespace",
                  f"TexturePairsCatalogue::Rows TexturePairsCatalogue::Rows{n}() {{",
                  "    return {rows, by_material, std::size(rows)};", "}", "}  // namespace title", ""]
        files[f"texture_pairs_catalogue/rows_{n}.cpp"] = "\n".join(lines)
    identity = [BANNER + INCLUDE, "namespace title {",
                f'const char* TexturePairsCatalogue::HeaderSha256() {{ return "{header_sha}"; }}',
                f'const char* TexturePairsCatalogue::DataSha256() {{ return "{data_sha}"; }}',
                "TexturePairsCatalogue::Rows TexturePairsCatalogue::Chunk(size_t index) {",
                "    switch (index) {"]
    for n in range(len(chunks)):
        identity.append(f"        case {n}: return Rows{n}();")
    identity += ["        default: return {nullptr, nullptr, 0};", "    }", "}", "}  // namespace title", ""]
    files["texture_pairs_catalogue/identity.cpp"] = "\n".join(identity)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", required=True, type=Path)
    parser.add_argument("--textures-dir", required=True, type=Path,
                        help="games/<t>/hle/graphics/textures (the catalogue header and partition directory)")
    parser.add_argument("--report", type=Path, help="optional JSON of the pairs with their containers")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--skip-missing", action="store_true", help="exit 77 when the archive is absent (ctest SKIP)")
    args = parser.parse_args()
    if args.skip_missing and not (args.archive / "CRASH.BH").exists():
        print(f"TexturePairsCatalogue: SKIP (archive absent: {args.archive})")
        return 77
    rows, header_sha, data_sha = pairs(args.archive)
    files = render(rows, header_sha, data_sha)
    kinds = collections.Counter(r["kind"] for r in rows)
    if args.report:
        args.report.write_text(json.dumps(dict(archive_header_sha256=header_sha, archive_data_sha256=data_sha,
                                                pairs=[dict(texture=f"{r['texture']:08x}", material=f"{r['material']:08x}",
                                                            kind=r["kind"], container=r["container"], slot=r["slot"])
                                                       for r in rows]), indent=1) + "\n")
    if args.check:
        bad = [name for name, text in files.items()
               if not (args.textures_dir / name).exists() or (args.textures_dir / name).read_text() != text]
        if bad:
            print("texture pair catalogue differs from the archive: " + ", ".join(bad), file=sys.stderr)
            return 1
        print(f"texture pair catalogue matches: {len(rows)} pairs ({dict(kinds)}) in {len(files)} files")
        return 0
    (args.textures_dir / "texture_pairs_catalogue").mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (args.textures_dir / name).write_text(text)
    print(f"wrote {len(files)} files: {len(rows)} pairs ({dict(kinds)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
